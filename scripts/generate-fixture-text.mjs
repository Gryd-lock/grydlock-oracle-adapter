/* global console, process */
/**
 * Generates `*.text.ts` companion modules that export the vendored fixture
 * JSON files' raw text as plain string literals (issue: incremental fixture
 * parsing).
 *
 * These are NOT a parsed representation of the fixture — just its exact
 * source characters, embedded as a JS string. That's what lets
 * scores.ts/destinations.ts obtain raw text to tokenize incrementally
 * without ever asking a bundler's `.json` import (or `JSON.parse`) to
 * materialize a full object graph, and without any Node-only fs/streaming
 * API in the shipped code path: a plain `export default "...";` string is
 * loadable by any bundler or the browser, identically to any other module.
 *
 * Run via `npm run generate:fixtures` after re-copying a vendored fixture
 * (see README's grydlock-testkit vendoring section). `tests/fixtureText.sync.test.ts`
 * fails the build if a generated file drifts from its source .json.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const fixturesDir = join(here, '..', 'src', 'fixtures', 'testkit');

export const FIXTURE_TEXT_FILES = [
  { json: 'scores.json', ts: 'scores.text.ts' },
  { json: 'destinations.json', ts: 'destinations.text.ts' },
];

export function generatedModuleSource(jsonFileName) {
  const raw = readFileSync(join(fixturesDir, jsonFileName), 'utf-8');
  return (
    `// Auto-generated by scripts/generate-fixture-text.mjs from ${jsonFileName}.\n` +
    `// Do not hand-edit; re-run \`npm run generate:fixtures\` instead.\n` +
    `export default ${JSON.stringify(raw)};\n`
  );
}

function main() {
  for (const { json, ts } of FIXTURE_TEXT_FILES) {
    const outPath = join(fixturesDir, ts);
    writeFileSync(outPath, generatedModuleSource(json), 'utf-8');
    console.log(`wrote ${outPath}`);
  }
}

// Only run as a script (not when imported by the drift-check test).
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
